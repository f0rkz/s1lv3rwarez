func drawText(dst *ebiten.Image, s string, x, y, scale int, c color.Color) {
	s = strings.ToUpper(s)
	for i := 0; i < len(s); i++ {
		drawGlyph(dst, s[i], x+i*6*scale, y, scale, c)
	}
}

func drawTextClipped(dst *ebiten.Image, s string, x, y, scale int, c color.Color, clip image.Rectangle) {
	s = strings.ToUpper(s)
	for i := 0; i < len(s); i++ {
		drawGlyphClipped(dst, s[i], x+i*6*scale, y, scale, c, clip)
	}
}

func drawGlyph(dst *ebiten.Image, ch byte, x, y, scale int, c color.Color) {
	drawGlyphClipped(dst, ch, x, y, scale, c, image.Rect(0, 0, virtualWidth, virtualHeight))
}

func drawGlyphClipped(dst *ebiten.Image, ch byte, x, y, scale int, c color.Color, clip image.Rectangle) {
	if ch >= 'a' && ch <= 'z' {
		ch -= 'a' - 'A'
	}
	rows, ok := glyphs[ch]
	if !ok {
		return
	}
	for yy, row := range rows {
		for xx := 0; xx < len(row); xx++ {
			if row[xx] == '1' {
				for py := 0; py < scale; py++ {
					for px := 0; px < scale; px++ {
						dx, dy := x+xx*scale+px, y+yy*scale+py
						if image.Pt(dx, dy).In(clip) && dx >= 0 && dx < virtualWidth && dy >= 0 && dy < virtualHeight {
							dst.Set(dx, dy, c)
						}
					}
				}
			}
		}
	}
}

func textWidth(s string, scale int) int {
	if len(s) == 0 {
		return 0
	}
	return len(s)*6*scale - scale
}
